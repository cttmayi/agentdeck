/**
 * 平台的「通用工作守则」——与岗位无关的那几条工作纪律（分批第 47 批）。
 *
 * ══════════════════════════════════════════════════════════════════
 * 它解决的是哪件事（使用者提的）
 * ══════════════════════════════════════════════════════════════════
 *
 * 使用者看起草者的三块（① 框架 / ② 身份 / ③ 任务）之后说：「发现有很多原则放在了
 * 框架和任务中。但我想尽量往身份去放，让它尽量和执行者通用」。
 *
 * 他说对了一半：确实有一批原则是**与岗位无关**的（只做被要求的事 / 依据来自素材 /
 * 产出落到文件里 …），它们被分散在 ① 的「护栏」与 ② 的纪律里。搬进 ② 之后，
 * 起草者、审核者、以及使用者新建的执行者就都能用同一份 —— 这就是"通用"。
 *
 * ══════════════════════════════════════════════════════════════════
 * 哪些**不能**搬进来（边界写死在这里，免得下次有人"顺手"加）
 * ══════════════════════════════════════════════════════════════════
 *
 * 下面这些属于**任务契约**，留在 ③（任务书）里：
 *
 *   · 数字型硬闸门（如指令 6000 字符上限）—— 模型对任务书里点名的数字遵从度更高；
 *   · 路径与产出形状（`skill/SKILL.md`、`agent/instructions.md`、UTF-8、不许 `..`）；
 *   · 验收判据（`## When to Use` / `## Procedure` 缺了入库会被拒）；
 *   · 只在某条流程里成立的约定（返工的"只改意见点到的地方"、`REFUSED.md`）。
 *
 * 判据很简单：**换一件活还成立 ⇒ 守则；只对这件活成立 ⇒ 任务书。**
 */

/**
 * 平台默认的工作守则。
 *
 * ⚠️ 刻意**很短**、只有四条：它每次都随第一句话发出去，而且会出现在使用者新建的
 *    agent 的指令框里（他一眼要能读完、能改、能删）。
 * ⚠️ 不含任何岗位词（"skill""审核""起草"）：这段要能被执行者直接用。
 */
export const GENERAL_WORK_CONDUCT = [
  '## 工作守则',
  '',
  '1. **只做被要求的事**，不要扩大范围；做完给一份报告：做了什么、结论、还有哪些不确定。',
  '2. **依据必须来自素材或现场**，不知道就不写，不编。',
  '3. **引用命令、参数、路径时回原文取**，不许凭印象重写。',
  '4. **产出落到文件里**，不只贴在回复里。',
].join('\n')

/** 守则的长度上限（写入口校验）。够写七八条，但不至于把身份块撑爆。 */
export const CONDUCT_MAX_CHARS = 4000

/**
 * 把守则接到身份文本后面 —— **拼装只在这一处**。
 *
 * 为什么要一个函数：内置 agent 的指令与"新建 agent 时的预填"必须是同一种形状。
 * 两处各拼一遍的话，某天一边改了顺序，表现是"内置的守则在前面、新建的在后面"，
 * 而这种差别没人会当成 bug 去查。
 *
 * @param role 岗位那一句（可以为空 = 只有守则；使用者新建 agent 时就是这样）
 * @param conduct 守则正文（缺省 = 平台默认）
 */
export function withConduct(role: string, conduct: string = GENERAL_WORK_CONDUCT): string {
  const head = role.trim()
  const body = conduct.trim()
  if (head === '') return body
  if (body === '') return head
  return `${head}\n\n${body}`
}
