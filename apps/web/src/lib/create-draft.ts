import { writable } from 'svelte/store'

/**
 * 「新建任务」那张表单**有没有被填过**。
 *
 * ══════════════════════════════════════════════════════════════════
 * 为什么它是 store，而不是一个 prop 或者一个组件内变量
 * ══════════════════════════════════════════════════════════════════
 *
 * 2026-10（D58 第二步）之后，那张表单住在「任务」页的**右栏**里，而"能不能离开
 * 这一栏"这件事由**外面**（任务页）决定：点左边列表里的一条任务、切看板、
 * 或者按顶栏的「刷新」，都会把表单从画面上换掉。
 *
 * 判据在表单里（只有它知道使用者填了什么），决定在外面（只有它知道要切到哪去），
 * 中间隔着一层渲染——所以只能用 store 传，不能用 prop。
 *
 * ⚠️ 不放 `view.ts`：那里是**路由**（地址 → 视图）。"表单脏了没有"与地址无关，
 *    混进去之后，读那个文件的人会以为它是一条路由规则。
 *
 * ⚠️ 语义是"**可能**有改动"，宁枉勿纵：勾了一个动作又取消勾选，这里仍然是
 *    `true`（问一句）。判得准一点要多存一份"原始快照"并逐字段比对，而代价是
 *    "使用者填了一半、界面上却什么都不问就换了页"——那才是真的丢东西。
 */
export const createDirty = writable(false)
