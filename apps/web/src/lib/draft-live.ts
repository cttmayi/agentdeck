/**
 * 「起草这一版还在跑吗」——决定审阅屏的草稿格显示**实时日志**还是**最后结果**。
 *
 * ══════════════════════════════════════════════════════════════════
 * 为什么单独抽出来（分批第 29 批）
 * ══════════════════════════════════════════════════════════════════
 *
 * 使用者报的：「在草稿-审核的循环中，只能看到审核过程，草稿的日志在UI上一直没有更新。」
 *
 * 量到的原因：审阅屏的草稿格默认显示**最后结果**（上一版写下的最后一段文本），
 * 而 `RunLog`（唯一带实时流的东西）藏在「完整日志」按钮后面。循环里起草者正在写下一版时，
 * 那一格要么是上一版的旧文本、要么是"还没有文本输出"——看起来就是"一直不更新"。
 *
 * 判据放进这个纯函数而不是散在 `.svelte` 里，是因为**只有它能被量**：
 * 组件里的行为要真浏览器夹具（还要恰好撞上"新版在跑"的竞态）才量得到，而这个函数的
 * 三种输入在单测里就能钉死。
 */

/** 已经结束的状态：这些才有"最后结果"可看。 */
const TERMINAL = ['completed', 'failed', 'cancelled']

/**
 * `status` 是界面此刻知道的起草状态；`null` = **还没收到终态**。
 *
 * ⚠️ `null` 必须算"在跑"：接上一条进行中的 run、或者刚跟到新一版，状态都还不知道；
 *    这时候显示实时日志永远是对的（日志里至少能看到它跑到哪儿了），
 *    而显示"最后结果"必然是**上一版**的旧文本——那正是使用者报的那个现象。
 *
 * ⚠️ 未知状态也按"在跑"处理：状态机将来加一个非终态值，这里不会因此把实时日志藏起来。
 *    宁可多显示一条实时日志，也不要把"还在跑"画成"已经写完"。
 */
export function draftIsLive(status: string | null | undefined): boolean {
  if (status === null || status === undefined || status === '') return true
  return !TERMINAL.includes(status)
}
