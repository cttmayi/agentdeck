/**
 * 新建任务页**唯一**要推导的那一件事：这条任务交给谁执行。
 *
 * ══════════════════════════════════════════════════════════════════
 * 这里原来是一整条链的推导（执行 → 审核 → 行动 → 返工）
 * ══════════════════════════════════════════════════════════════════
 *
 *   · **返工**（D124）先退场；
 *   · **动作**（D123）再退场；
 *   · **审核 run 与判决**（D125）最后退场。
 *
 *   于是这一页只剩一个问题：**交给谁**（一个智能体，或者一个智能体组——组提供
 *   它自己的执行者）。
 *
 * ⚠️ 但它为什么仍然是"一个独立纯函数文件、而不是 `.svelte` 里的几个 `$:`"这条
 *   理由**没有过期**：`apps/web` 没有组件级测试的跑法（Svelte 组件在 node 里渲
 *   不出来），而"从组的成员里挑出执行者"这件事判错了不会有任何报错——它只会让
 *   任务被派给错的人。判据放进纯函数，用 `node --test` 钉住。
 */

/*
 * ⚠️ 2026-11（S3）：这里原来是 `groupExecutor(members)`——"组的执行者是成员里那个
 *   `role === 'executor'`"。智能体组退场 ⇒ 没有组可展开，函数删。
 *
 *   ⚠️ 它当年那条"按角色找、不按位置找"的判据仍然是本仓库的默认做法：**从一组
 *   人里挑某个角色，要按角色挑，不要按顺序猜第一个**。
 */

/**
 * **能派活/能聊天的候选**：所有**不是平台内置岗位**的智能体。
 *
 * ══════════════════════════════════════════════════════════════════
 * 2026-11（S4，D127）：判据从角色换成"有没有内置岗位"
 * ══════════════════════════════════════════════════════════════════
 *
 * 原来是 `role === 'executor'`——"审核者不该接任务"那类判断。**角色退场**之后，
 * 唯一还不能派活的是**平台内置的岗位**（起草者 / 记忆整理 / 生成者 / 沉淀审核者）：
 * 它们按自己的岗位说明干活，被派用户任务只会跑偏。
 *
 * ⚠️ 而在角色退场的世界里，**用户建的 agent 一律可以接任务**——包括他自己在指令里
 *   写成"我是审阅者"的那种。平台不再声称知道"这个人该干什么"；派错了由人自己发现
 *   （真机上当年那个"审核者接到实现任务、写了一份'不符合要求'的结论"的坑，现在
 *   靠的是**这一层不再假装懂**，而不是靠 role 拦）。
 */
export function executorCandidates(agents: readonly Agent[]): Agent[] {
  /*
   * ★ 2026-11（D145）：判据换成**接入点**（`entries` 里有 `task`），与 daemon 的
   *   `canBeDispatched` 同一句。改之前这条用的是 `builtinKind === undefined`——
   *   同一个问题在界面、设默认、接口层各有一个判据，而"半内置"正好从缝里钻过去。
   */
  return agents.filter((a) => hasEntry(a, 'task'))
}

