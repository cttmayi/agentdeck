import { writable, type Readable } from 'svelte/store'
import type { IconId } from './icons.ts'
import type { ViewName } from './view.ts'

/**
 * 「这一页的动作」——顶栏里紧跟页名的那排按钮。
 *
 * ══════════════════════════════════════════════════════════════════
 * 为什么动作不是写在顶栏里，而是各视图登记上来
 * ══════════════════════════════════════════════════════════════════
 *
 * 动作绑着**各视图自己的状态与函数**（`creating`、`refresh`、`openPanel`…），
 * 所以它只能由视图提供。剩下的问题只是"怎么把它送到顶栏去"：
 *
 * - **把动作表写进外壳**：每加一个页面动作就要改两处（视图 + 外壳），而且外壳
 *   从此要懂业务——`App.svelte` 顶上那句"外壳一旦开始懂业务，改一个视图就要读
 *   整个外壳"说的就是这件事。
 * - **各视图各渲染一个顶栏**：切页时顶栏跟着重建，品牌与全局控件会闪，
 *   而且"顶栏只有一个"这件事就没人保证了。
 * - **登记（这里）**：视图挂载时把自己的动作交上来，卸载时收回。外壳只认
 *   "当前是谁的动作"，不认识任何一个具体按钮。
 *
 * ══════════════════════════════════════════════════════════════════
 * ★ 登记**按视图名**存，不是"谁后登记谁的"
 * ══════════════════════════════════════════════════════════════════
 *
 * `{#if}` 换页时，旧组件的销毁与新组件的挂载**顺序不是我们可以依赖的东西**
 * （Svelte 现在是一种顺序，将来可能是另一种）。如果这里只存"最后登记的那一份"，
 * 那么"新页先登记、旧页后卸载并把内容清掉"这种顺序就会让顶栏**空着**——症状是
 * "切过去之后按钮不见了，再切一次又好了"，属于最难复现的一类。
 *
 * 所以存的是 `{ view, actions }`：读的一侧只认 `view === 当前视图`，
 * 清的一侧也只清自己那一份。两种情况都不会互相踩。
 *
 * ══════════════════════════════════════════════════════════════════
 * ★ 标签要在语言切换时重新登记
 * ══════════════════════════════════════════════════════════════════
 *
 * 视图那边把它写在 `$:` 里并读 `$t(...)`，所以语言一变就会重新登记一遍
 * ——**是替换，不是追加**（`setPageActions` 是整体覆盖）。追加的话切一次语言
 * 就会多出一排按钮，切回来再多一排。
 */

export type PageAction = {
  /**
   * 稳定标识，在**同一个视图内部**唯一。
   *
   * ⚠️ 它现在只用于 `{#each ... (action.id)}` 的键：Svelte 靠它认"这还是同一个
   *    按钮"，没有它时同一位置的按钮会被当成新节点重建（焦点与 hover 状态会丢）。
   *    所以**别拿标签当键**——标签会跟着语言变。
   */
  id: string
  /** 按钮上的字。跟着 `$t(...)` 走。 */
  label: string
  /**
   * 视觉权重。
   *
   * ⚠️ 2026-10（D59）之后这一排是一**条工具条**（见 `app.css` 里 `.page-actions`
   *    那一段），所以 `kind` 只区分两件事：
   *    · `primary` = 这一页的**主线动作**（新建 / 安装）——文字用强调色 + 半粗；
   *    · 其余（`secondary` / `ghost`）在这一排里长得一样：普通文字色。
   *    呈现模式那两颗（列表 / 看板）不再靠"更轻"来区分，而是靠 `active` 的
   *    **实心底**——那才是"我是哪一种"该有的信号（旧的三种重量里，ghost 与
   *    secondary 的底色对比只有 1.14:1，等于没画）。
   */
  kind?: 'primary' | 'secondary' | 'ghost'
  /** 互斥的呈现模式（列表 / 看板）里，标出**当前**那一个；也是"正在这一栏"。 */
  active?: boolean
  /**
   * 动作前面那个小图标（可选，见 `lib/icons.ts`）。
   *
   * ★ 只给"词条短到没有形状"的那几个用（新建 / 刷新 / 列表 / 看板）。不写就
   *   只有文字——**不要为了整齐给每个按钮都塞一个图标**：中文词条本身好认，
   *   一排小图标反而变成噪点。
   *
   * ⚠️ 传进来的是 `IconId`（那四个之一），写错是编译错误。
   */
  icon?: IconId
  disabled?: boolean
  /** 悬停提示。省缺时不给 `title`（不要给每个按钮都塞一句废话）。 */
  title?: string
  onActivate: () => void
}

type Registered = { view: ViewName; actions: PageAction[] }

const store = writable<Registered | null>(null)

/** 只读：顶栏读它。写入一律走下面两个函数，免得别处 `set` 出个形状不对的东西。 */
export const pageActions: Readable<Registered | null> = { subscribe: store.subscribe }

/**
 * 登记（整体覆盖）**这一个视图**的动作。
 *
 * 覆盖而不是合并：视图每次都交上**完整**的一份，所以"某个按钮不该出现了"
 * （比如聊天正在起草、新建面板已经打开）只需要不再把它放进数组里。
 */
export function setPageActions(view: ViewName, actions: PageAction[]): void {
  store.set({ view, actions })
}

/**
 * 收回**这一个视图**的登记（组件卸载时调）。
 *
 * ⚠️ 只清 `view` 对得上的那一份：换页时旧视图的卸载可能发生在**新视图登记之后**，
 *    无条件清空会把新页的按钮一起清掉。
 */
export function clearPageActions(view: ViewName): void {
  store.update((cur) => (cur?.view === view ? null : cur))
}

/** 当前视图该显示哪些动作（登记的不是这一页就一个都不显示）。 */
export function actionsFor(current: Registered | null, view: ViewName): PageAction[] {
  return current?.view === view ? current.actions : []
}

/** 测试用：把 store 恢复到"没人登记"的初始态。 */
export function resetPageActions(): void {
  store.set(null)
}
