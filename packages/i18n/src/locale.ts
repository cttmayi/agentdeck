/**
 * 界面语言（D39）。
 *
 * ══════════════════════════════════════════════════════════════════
 * 只翻"界面"，不翻"给模型看的东西"
 * ══════════════════════════════════════════════════════════════════
 *
 * 使用者定的范围：**菜单、按钮、标签、说明**跟着语言走；而"交给模型的那段话"
 * （第一句话模版、判决契约、内置审核标准）**不翻译**——它们仍是中文。
 *
 * 那"看不懂模型的答复"怎么办：第一句话里加一条**语言指令**（`{{language}}`），
 * 让模型用你选的语言回答。这条在 `packages/agent-core` 那边落地，与本文件无关。
 *
 * ══════════════════════════════════════════════════════════════════
 * 三类文字的分界线（这是本功能最容易做糊的地方）
 * ══════════════════════════════════════════════════════════════════
 *
 *   1. **界面文案** ⇒ 有 zh/en 两份，跟着 `locale` 走（本包负责）；
 *   2. **契约值 / 标识符**（`pass`、`meets_criteria`、`comment.create`、
 *      `in_progress`、`general-review`、`claude`）⇒ **永不翻译**：它们出现在
 *      判决 JSON、接口与日志里，是机器值。界面上的做法是**值照旧等宽显示，
 *      旁边加一个本地化的显示名**（见 `term.*` 那批词条）；
 *   3. **历史文本**（已经写进库的日志、通知、判决里的话）⇒ **不重译**。它们是
 *      "当时发生了什么"的原始记录，跟着语言变会让人以为记录本身变了。
 */
export type Locale = 'zh' | 'en'

export const LOCALES: readonly Locale[] = ['zh', 'en']

export function isLocale(value: unknown): value is Locale {
  return value === 'zh' || value === 'en'
}

/**
 * 语言自己的名字——**不翻译**。
 *
 * 语言切换器里永远用该语言自己的写法（中文 / English）：一个只看得懂英文的人
 * 在中文界面里要能找到 "English"，反过来也一样。
 */
export const LOCALE_LABEL: Record<Locale, string> = {
  zh: '中文',
  en: 'English',
}

/** 默认语言。中文是这个项目的第一语言，也是所有既有数据与文档的语言。 */
export const DEFAULT_LOCALE: Locale = 'zh'
