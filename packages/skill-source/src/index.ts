/**
 * `@agentdeck/skill-source` —— **技能包的取包规则**，一份、两处用。
 *
 * ══════════════════════════════════════════════════════════════════
 * 为什么它不在 daemon 里（2026-10 抽出）
 * ══════════════════════════════════════════════════════════════════
 *
 * 这套规则原来住在 `apps/daemon/src/skill-source.ts`，只有 daemon 一个调用方，
 * 那样是合理的：装技能是**本机**的事。
 *
 * 后来多了一个调用方：**推荐技能目录的同步工具**（`tools/skill-catalog-sync/`，
 * 命令是 `pnpm run sync-skills`）——它要把清单里的 GitHub 技能抓下来、校验后写进
 * 一个目录，供远端服务当公共目录读。而要做的判断与 daemon 一模一样：是不是
 * GitHub 主机、https、每一跳跳转都校验、限额、目录里必须有 `SKILL.md`、slug 怎么收敛。
 *
 * ★ **不能让抓取那一侧另写一份**。这个仓库最忌讳的不一致就是"目录说 A、daemon
 *   按 B 解析"——而这一次的后果特别具体：**目录会把一份 daemon 装不进来的东西
 *   列成"推荐"**，使用者点下去才失败，而失败原因看起来像"平台坏了"。
 *
 * 所以规则上提到这个包：daemon（装技能）与那个同步工具（抓推荐清单）共用同一份
 * 实现。⚠️ 抓取工具与远端服务之间**没有**代码依赖——它们只靠一个目录相连。
 *
 * ⚠️ 它与 `apps/daemon/src/tool-source.ts`（工具包的取包规则）是**两条并行的路**，
 *    刻意没有合并：技能是一个 `SKILL.md` 目录，工具包是一份 `tool.json` 清单
 *    加入口脚本，两者的判据、限额、形状都不同。共用的是下面这些**基础件**
 *    （`MAX_*` 限额、`toSlug` / `assertValidSlug` 收敛、`isProbablyText`、
 *    `SkillSourceError`），而不是"取一个包"这件事本身。
 */

